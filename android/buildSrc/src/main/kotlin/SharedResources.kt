import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.tasks.InputDirectory
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import java.io.File

/**
 * The iOS app's resources, used by the Android app without copies in git:
 * show and host photos and the brand images (Assets.xcassets imagesets) as
 * drawables, the Manrope fonts as font resources.
 *
 * Android resource names are lower snake case, so `ShowArtBassTime` becomes
 * `R.drawable.show_art_bass_time` and `Manrope-ExtraBold.ttf`
 * `R.font.manrope_extrabold`. [SharedImages] (generated alongside) maps the
 * imageset names that schedule.json uses to those drawables.
 */
abstract class SyncSharedResources : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val iosResources: DirectoryProperty

    @get:OutputDirectory
    abstract val resOutput: DirectoryProperty

    @get:OutputDirectory
    abstract val kotlinOutput: DirectoryProperty

    @TaskAction
    fun sync() {
        val res = resOutput.get().asFile.apply { deleteRecursively() }
        val drawables = File(res, "drawable-nodpi").apply { mkdirs() }
        val fonts = File(res, "font").apply { mkdirs() }
        val source = iosResources.get().asFile

        val images = sortedMapOf<String, String>()
        val vectors = File(res, "drawable").apply { mkdirs() }
        File(source, "Assets.xcassets").listFiles { f -> f.name.endsWith(".imageset") }!!.forEach { set ->
            set.listFiles { f -> f.extension.lowercase() == "svg" }?.firstOrNull()?.let { svg ->
                File(vectors, "${snakeCase(set.nameWithoutExtension)}.xml").writeText(vectorDrawable(svg.readText()))
                return@forEach
            }
            val image = set.listFiles { f -> f.extension.lowercase() in setOf("png", "jpg", "jpeg") }
                ?.minByOrNull { it.name } ?: return@forEach
            val name = set.nameWithoutExtension
            val resName = snakeCase(name)
            image.copyTo(File(drawables, "$resName.${image.extension.lowercase().replace("jpeg", "jpg")}"), overwrite = true)
            images[name] = resName
        }

        File(source, "Fonts").listFiles { f -> f.extension == "ttf" }!!.forEach { font ->
            val resName = font.nameWithoutExtension.lowercase().replace('-', '_')
            font.copyTo(File(fonts, "$resName.ttf"), overwrite = true)
        }

        val kotlin = kotlinOutput.get().asFile.apply { deleteRecursively() }
        val file = File(kotlin, "cz/slowdownradijo/app/data/SharedImages.kt")
        file.parentFile.mkdirs()
        file.writeText(buildString {
            appendLine("// Generated by buildSrc/SharedResources.kt from the iOS Assets.xcassets.")
            appendLine("package cz.slowdownradijo.app.data")
            appendLine()
            appendLine("import cz.slowdownradijo.app.R")
            appendLine()
            appendLine("/** The bundled photos by their iOS imageset name, as schedule.json names them. */")
            appendLine("object SharedImages {")
            appendLine("    val byName: Map<String, Int> = mapOf(")
            images.forEach { (name, res) -> appendLine("        \"$name\" to R.drawable.$res,") }
            appendLine("    )")
            appendLine()
            appendLine("    fun drawable(name: String?): Int? = name?.let(byName::get)")
            appendLine("}")
        })
    }

    /**
     * The iOS icons are simple SVGs (stroked or filled paths on a viewBox):
     * the same paths as an Android vector drawable. Template icons on iOS,
     * so the colour is white here and the app tints them.
     */
    private fun vectorDrawable(svg: String): String {
        fun attr(tag: String, name: String) = Regex("""\b$name="([^"]*)"""").find(tag)?.groupValues?.get(1)
        val root = Regex("<svg[^>]*>").find(svg)!!.value
        val box = attr(root, "viewBox")!!.split(Regex("[ ,]+")).map { it.toFloat() }
        val paths = Regex("<path[^>]*>").findAll(svg).joinToString("\n") { match ->
            val tag = match.value
            val stroke = attr(tag, "stroke")?.takeIf { it != "none" }
            val fill = attr(tag, "fill")?.takeIf { it != "none" }
            buildString {
                append("    <path android:pathData=\"${attr(tag, "d")}\"")
                if (fill != null) append("\n        android:fillColor=\"#FFFFFFFF\"")
                if (stroke != null) {
                    append("\n        android:strokeColor=\"#FFFFFFFF\"")
                    append("\n        android:strokeWidth=\"${attr(tag, "stroke-width") ?: "1"}\"")
                    attr(tag, "stroke-linecap")?.let { append("\n        android:strokeLineCap=\"$it\"") }
                    attr(tag, "stroke-linejoin")?.let { append("\n        android:strokeLineJoin=\"$it\"") }
                }
                append(" />")
            }
        }
        return """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by buildSrc/SharedResources.kt from the iOS imageset's SVG. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${box[2]}dp" android:height="${box[3]}dp"
    android:viewportWidth="${box[2]}" android:viewportHeight="${box[3]}">
$paths
</vector>
"""
    }

    private fun snakeCase(name: String): String =
        name.replace(Regex("([a-z0-9])([A-Z])"), "$1_$2")
            .replace(Regex("([A-Z]+)([A-Z][a-z])"), "$1_$2")
            .lowercase()
}

/** schedule.json (the show catalogue) as an app asset. */
abstract class SyncSharedAssets : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val iosResources: DirectoryProperty

    @get:OutputDirectory
    abstract val output: DirectoryProperty

    @TaskAction
    fun sync() {
        val out = output.get().asFile.apply { deleteRecursively(); mkdirs() }
        File(iosResources.get().asFile, "schedule.json").copyTo(File(out, "schedule.json"), overwrite = true)
    }
}
