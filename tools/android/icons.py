#!/usr/bin/env python3
"""The Android launcher icon from the iOS AppIcon (icon-1024.png).

Writes an adaptive icon (the logo on a transparent foreground layer, over
the icon's own purple as the background colour) and legacy square/round
PNGs for each density into android/app/src/main/res. Run again when the
iOS icon changes.
"""
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
ICON = ROOT / "SlowDownRadijo/Resources/Assets.xcassets/AppIcon.appiconset/icon-1024.png"
RES = ROOT / "android/app/src/main/res"
DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}

icon = Image.open(ICON).convert("RGBA")
bg = icon.getpixel((8, 8))
hex_bg = "#{:02X}{:02X}{:02X}".format(*bg[:3])

# The logo spans about 74% of the iOS icon; the adaptive icon's safe zone
# is a 66dp circle in 108dp, so the whole icon goes in at 66dp (the logo
# itself then about 49dp).
for name, scale in DENSITIES.items():
    folder = RES / f"mipmap-{name}"
    folder.mkdir(parents=True, exist_ok=True)
    fg_size = round(108 * scale)
    logo = round(66 * scale)
    fg = Image.new("RGBA", (fg_size, fg_size), (0, 0, 0, 0))
    # Only the logo, not the purple square: mask out the background colour.
    small = icon.resize((logo, logo), Image.LANCZOS)
    px = small.load()
    for y in range(logo):
        for x in range(logo):
            r, g, b, a = px[x, y]
            d = abs(r - bg[0]) + abs(g - bg[1]) + abs(b - bg[2])
            if d < 40:
                px[x, y] = (r, g, b, 0)
            elif d < 120:
                px[x, y] = (r, g, b, int(a * (d - 40) / 80))
    off = (fg_size - logo) // 2
    fg.alpha_composite(small, (off, off))
    fg.save(folder / "ic_launcher_foreground.png", optimize=True)

    legacy = round(48 * scale)
    square = icon.resize((legacy, legacy), Image.LANCZOS)
    mask = Image.new("L", (legacy, legacy), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, legacy - 1, legacy - 1), radius=legacy // 6, fill=255)
    rounded = Image.new("RGBA", (legacy, legacy), (0, 0, 0, 0))
    rounded.paste(square, (0, 0), mask)
    rounded.save(folder / "ic_launcher.png", optimize=True)
    circle = Image.new("L", (legacy, legacy), 0)
    ImageDraw.Draw(circle).ellipse((0, 0, legacy - 1, legacy - 1), fill=255)
    round_icon = Image.new("RGBA", (legacy, legacy), (0, 0, 0, 0))
    round_icon.paste(square, (0, 0), circle)
    round_icon.save(folder / "ic_launcher_round.png", optimize=True)

anydpi = RES / "mipmap-anydpi-v26"
anydpi.mkdir(parents=True, exist_ok=True)
xml = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/android/icons.py from the iOS AppIcon. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
"""
(anydpi / "ic_launcher.xml").write_text(xml)
(anydpi / "ic_launcher_round.xml").write_text(xml)
(RES / "values/ic_launcher_background.xml").write_text(
    f'<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">{hex_bg}</color>\n</resources>\n'
)
print("background", hex_bg)
