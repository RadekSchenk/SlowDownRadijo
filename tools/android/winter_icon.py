"""The winter launcher icon for Android; run as `icons.py --winter`.

Legacy square/round PNGs from the iOS AppIconWinter. The adaptive icon's
foreground is BrandAssets/WinterIcon/foreground-1024.png — the iOS winter
icon without its background (logo, bauble, snowflakes; exported from Figma
"Advent ❄︎") — placed like the normal icon: the whole 1024 square in the
66dp safe zone of 108dp. The bauble's thread is drawn on up to the top
edge, so it hangs from the icon's edge whatever shape the launcher cuts.
The background is the same night gradient as on iOS, as a drawable.

Which icon the app has is set in AndroidManifest.xml (docs/winter.md).
"""
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
IOS = ROOT / "SlowDownRadijo/Resources/Assets.xcassets/AppIconWinter.appiconset/icon-1024.png"
FOREGROUND = ROOT / "BrandAssets/WinterIcon/foreground-1024.png"
RES = ROOT / "android/app/src/main/res"
DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
# Figma's icon I4, top to bottom.
TOP, BOTTOM = "#221A50", "#463A8C"
# The thread in the 1024 icon: centred on x 518, 4 wide, white at 55 %.
THREAD_X, THREAD_W, THREAD_ALPHA = 518 / 1024, 4 / 1024, round(255 * 0.55)

icon = Image.open(IOS).convert("RGBA")
foreground = Image.open(FOREGROUND).convert("RGBA")

for name, scale in DENSITIES.items():
    folder = RES / f"mipmap-{name}"
    folder.mkdir(parents=True, exist_ok=True)
    fg_size = round(108 * scale)
    logo = round(66 * scale)
    off = (fg_size - logo) // 2
    fg = Image.new("RGBA", (fg_size, fg_size), (0, 0, 0, 0))
    x = off + THREAD_X * logo
    w = max(1.0, THREAD_W * logo)
    ImageDraw.Draw(fg).rectangle((x - w / 2, 0, x + w / 2, off + 1), fill=(255, 255, 255, THREAD_ALPHA))
    fg.alpha_composite(foreground.resize((logo, logo), Image.LANCZOS), (off, off))
    fg.save(folder / "ic_launcher_winter_foreground.png", optimize=True)

    legacy = round(48 * scale)
    square = icon.resize((legacy, legacy), Image.LANCZOS)
    for suffix, round_shape in (("", False), ("_round", True)):
        mask = Image.new("L", (legacy, legacy), 0)
        draw = ImageDraw.Draw(mask)
        if round_shape:
            draw.ellipse((0, 0, legacy - 1, legacy - 1), fill=255)
        else:
            draw.rounded_rectangle((0, 0, legacy - 1, legacy - 1), radius=legacy // 6, fill=255)
        out = Image.new("RGBA", (legacy, legacy), (0, 0, 0, 0))
        out.paste(square, (0, 0), mask)
        out.save(folder / f"ic_launcher_winter{suffix}.png", optimize=True)

(RES / "drawable").mkdir(exist_ok=True)
(RES / "drawable/ic_launcher_winter_background.xml").write_text(f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/android/winter_icon.py (icons.py, winter). -->
<shape xmlns:android="http://schemas.android.com/apk/res/android">
    <gradient android:angle="270" android:startColor="{TOP}" android:endColor="{BOTTOM}" />
</shape>
""")
# Themed (monochrome) icons keep the plain logo: flakes and the bauble's
# thread would read as noise in one colour.
xml = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/android/winter_icon.py (icons.py, winter). -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_winter_background" />
    <foreground android:drawable="@mipmap/ic_launcher_winter_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
"""
anydpi = RES / "mipmap-anydpi-v26"
(anydpi / "ic_launcher_winter.xml").write_text(xml)
(anydpi / "ic_launcher_winter_round.xml").write_text(xml)
print("winter icon written")
